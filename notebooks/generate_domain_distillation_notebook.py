    "    SPECIAL_TOKENS = [\"[PAD]\", \"[UNK]\", \"[CLS]\", \"[SEP]\", \"[MASK]\", \"[COORD]\", \"[SPELL]\", \"[MOB]\", \"[QUEST]\"]\n",
    "\n",
    "    def __init__(self, vocab: Optional[Dict[str, int]] = None):\n",
    "        self.vocab = vocab or {}\n",
    "        self.inv_vocab = {v: k for k, v in self.vocab.items()}\n",
    "        if not self.vocab:\n",
    "            self._init_default_vocab()\n",
