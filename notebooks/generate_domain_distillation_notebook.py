    "class DofusBrainTransformer(nn.Module):\n",
    "    def __init__(self, vocab_size: int = 4096, d_model: int = 256, nhead: int = 8, num_layers: int = 6, dim_feedforward: int = 768, max_seq_len: int = 128, num_policy_classes: int = 4, num_intent_classes: int = 12, dropout: float = 0.1):\n",
    "        super().__init__()\n",
    "        self.token_emb = nn.Embedding(vocab_size, d_model, padding_idx=0)\n",
    "        self.pos_emb = nn.Embedding(max_seq_len, d_model)\n",
    "        self.blocks = nn.ModuleList([DofusTransformerBlock(d_model, nhead, dim_feedforward, dropout) for _ in range(num_layers)])\n",
    "        self.ln_f = nn.LayerNorm(d_model)\n",
    "        self.policy_head = nn.Linear(d_model, num_policy_classes)\n",
    "        self.intent_head = nn.Linear(d_model, num_intent_classes)\n",
    "        self.value_head = nn.Linear(d_model, 1)\n",
    "\n",
    "    def forward(self, input_ids: torch.Tensor, attention_mask: Optional[torch.Tensor] = None) -> Dict[str, torch.Tensor]:\n",
    "        batch_size, seq_len = input_ids.shape\n",
    "        pos = torch.arange(0, seq_len, dtype=torch.long, device=input_ids.device).unsqueeze(0)\n",
    "        x = self.token_emb(input_ids) + self.pos_emb(pos)\n",
    "        key_padding_mask = (input_ids == 0) if attention_mask is None else (attention_mask == 0)\n",
    "        for blk in self.blocks:\n",
    "            x = blk(x, key_padding_mask=key_padding_mask)\n",
    "        x = self.ln_f(x)\n",
    "        cls_rep = x[:, 0, :]\n",
    "        return {\n",
    "            \"intent_logits\": self.intent_head(cls_rep),\n",
    "            \"policy_logits\": self.policy_head(cls_rep),\n",
    "            \"value_pred\": self.value_head(cls_rep),\n",
    "            \"cls_rep\": cls_rep,\n",
    "        }\n",
