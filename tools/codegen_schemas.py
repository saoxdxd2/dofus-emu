#!/usr/bin/env python3
"""Single-source contract codegen: one JSON Schema set -> four typed runtimes.

Why this exists
---------------
The bridge envelope, the proxy telemetry document and the tool-call contract were
each hand-parsed in a different language. The C# side guessed with
``Regex.Match(json, "\\"id\\"\\s*:...")``, which cannot tell a top-level ``id`` from
an ``args.id``; the Go relay built JSON with ``fmt.Fprintf`` templates; the JS
agent read whatever the page supplied; and Python used ad-hoc ``dict.get`` chains.
Four parsers means four opinions about what a valid payload is, and the disagreement
is only discovered in production.

This tool owns the contract. The schemas in ``schema/`` are canonical; the outputs
below are generated, checked in, and verified byte-for-byte by ``--check`` (which the
gate runs). Editing a generated file is always wrong: change the schema and re-run.

    python tools/codegen_schemas.py            # write every target
    python tools/codegen_schemas.py --check    # exit 1 on drift, write nothing
    python tools/codegen_schemas.py --only csharp

Targets
-------
    dofus-network/generated/contracts.py       typed dataclasses + validators
    scripts/generated/contracts_gen.go         structs + validators (package main)
    desktop/generated/contracts.cs             classes over DofusFarm.Json.JsonText
    scripts/contracts.generated.js             browser/module validators

The generator is intentionally dependency-free and deterministic: sorted inputs,
no timestamps, no environment values, so a rebuild is bit-identical.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_DIR = ROOT / "schema"

TARGETS = {
    "python": ROOT / "dofus-network" / "generated" / "contracts.py",
    "go": ROOT / "scripts" / "contracts_gen.go",
    "csharp": ROOT / "desktop" / "generated" / "contracts.cs",
    "js": ROOT / "scripts" / "contracts.generated.js",
}
MANIFEST = SCHEMA_DIR / "generated.manifest.json"

HEADER = "Code generated by tools/codegen_schemas.py from schema/*.schema.json. DO NOT EDIT."

PY_SCALARS = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}
PY_CONTAINERS = {"object": "Dict[str, Any]", "array": "List[Any]"}
GO_SCALARS = {"string": "string", "integer": "int64", "number": "float64", "boolean": "bool"}
GO_CONTAINERS = {"object": "map[string]interface{}", "array": "[]interface{}"}
CS_SCALARS = {"string": "string", "integer": "long", "number": "double", "boolean": "bool"}
CS_CONTAINERS = {"object": "Dictionary<string, object>", "array": "List<object>"}


# -- schema helpers ---------------------------------------------------------

def load_schemas() -> List[Dict[str, Any]]:
    schemas = []
    for path in sorted(SCHEMA_DIR.glob("*.schema.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        data["_file"] = path.name
        data["_source"] = path.read_bytes()
        schemas.append(data)
    if not schemas:
        raise SystemExit("no schema/*.schema.json files found")
    return schemas


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.replace("-", "_").split("_"))


def snake(name: str) -> str:
    return name.replace("-", "_")


def fields_of(schema: Dict[str, Any]) -> List[Tuple[str, Dict[str, Any], bool]]:
    required = set(schema.get("required") or [])
    out = []
    for key in sorted(schema.get("properties") or {}):
        spec = schema["properties"][key]
        if "$ref" in spec or spec.get("type") not in set(PY_SCALARS) | set(PY_CONTAINERS):
            raise SystemExit("%s.%s: unsupported schema construct" % (schema["$id"], key))
        out.append((key, spec, key in required))
    # Required fields first so a dataclass can give every optional field a default.
    out.sort(key=lambda item: (not item[2], item[0]))
    return out


def extra_policy(schema: Dict[str, Any]) -> bool:
    """True when unknown keys are rejected."""
    return schema.get("additionalProperties") is False


# -- Python -----------------------------------------------------------------

def emit_python(schemas: List[Dict[str, Any]]) -> str:
    lines: List[str] = ['"""%s"""' % HEADER, "", "from __future__ import annotations", "",
                        "from dataclasses import dataclass", "from typing import Any, Dict, List, Optional",
                        "", "", "class ContractError(ValueError):", "    \"\"\"A payload did not satisfy its canonical schema.\"\"\"",
                        "", "    def __init__(self, contract: str, errors: List[str]) -> None:",
                        "        self.contract = contract", "        self.errors = list(errors)",
                        "        super().__init__(\"%s: %s\" % (contract, \"; \".join(self.errors)))", ""]
    checker_names = []
    for schema in schemas:
        name = schema["$id"]
        cls = pascal(name)
        checker = "validate_" + snake(name)
        checker_names.append(checker)
        keys = [key for key, _spec, _req in fields_of(schema)]
        lines.append("_%s_KEYS = frozenset(%r)" % (name.upper(), tuple(sorted(keys))))
        lines.append("")
        lines.append("")
        lines.append("@dataclass")
        lines.append("class %s:" % cls)
        for key, spec, _req in fields_of(schema):
            base = PY_SCALARS.get(spec["type"]) or PY_CONTAINERS[spec["type"]]
            lines.append("    %s: Optional[%s] = None" % (snake(key), base))
        lines.append("")
        lines.append("    @classmethod")
        lines.append("    def from_dict(cls, value: Any) -> \"%s\":" % cls)
        lines.append("        errors = %s(value)" % checker)
        lines.append("        if errors:")
        lines.append("            raise ContractError(%r, errors)" % name)
        lines.append("        data = value")
        lines.append("        return cls(" + ", ".join(
            "%s=data.get(%r)" % (snake(key), key) for key, _spec, _req in fields_of(schema)) + ")")
        lines.append("")
        lines.append("    def to_dict(self) -> Dict[str, Any]:")
        lines.append("        out: Dict[str, Any] = {}")
        for key, _spec, is_required in fields_of(schema):
            if is_required:
                lines.append("        if self.%s is not None:" % snake(key))
                lines.append("            out[%r] = self.%s" % (key, snake(key)))
            else:
                lines.append("        if self.%s is not None:" % snake(key))
                lines.append("            out[%r] = self.%s" % (key, snake(key)))
        lines.append("        return out")
        lines.append("")
        lines.append("")
        lines.extend(_python_validator(name, schema))
        lines.append("")
        lines.append("")
        lines.append("def parse_%s(value: Any) -> %s:" % (snake(name), cls))
        lines.append("    \"\"\"Validate then build the typed value; raises ContractError on a violation.\"\"\"")
        lines.append("    return %s.from_dict(value)" % cls)
        lines.append("")
        lines.append("")

    lines.append("CONTRACTS = {")
    for schema in schemas:
        lines.append("    %r: %s," % (schema["$id"], "validate_" + snake(schema["$id"])))
    lines.append("}")
    lines.append("")
    lines.append("")
    lines.append("def validate(contract: str, value: Any) -> List[str]:")
    lines.append("    \"\"\"Validate by schema id, e.g. validate(\"tool_call\", payload).\"\"\"")
    lines.append("    checker = CONTRACTS.get(contract)")
    lines.append("    if checker is None:")
    lines.append("        return [\"unknown contract %r\" % (contract,)]")
    lines.append("    return checker(value)")
    lines.append("")
    return "\n".join(lines)


def _python_type_check(expr: str, kind: str) -> str:
    if kind == "string":
        return "isinstance(%s, str)" % expr
    if kind == "integer":
        return "isinstance(%s, int) and not isinstance(%s, bool)" % (expr, expr)
    if kind == "number":
        return "isinstance(%s, (int, float)) and not isinstance(%s, bool)" % (expr, expr)
    if kind == "boolean":
        return "isinstance(%s, bool)" % expr
    if kind == "object":
        return "isinstance(%s, dict)" % expr
    if kind == "array":
        return "isinstance(%s, list)" % expr
    raise AssertionError(kind)


def _python_validator(name: str, schema: Dict[str, Any]) -> List[str]:
    fn = "validate_" + snake(name)
    lines = ["def %s(value: Any) -> List[str]:" % fn,
             "    \"\"\"Return every violation of the %s schema; empty means valid.\"\"\"" % name,
             "    errors: List[str] = []",
             "    if not isinstance(value, dict):",
             "        return [\"expected an object, got \" + type(value).__name__]"]
    required = [key for key, _spec, req in fields_of(schema) if req]
    if required:
        lines.append("    for key in %r:" % (tuple(sorted(required)),))
        lines.append("        if key not in value:")
        lines.append("            errors.append(\"missing required field %r\" % (key,))")
    if extra_policy(schema):
        lines.append("    for key in sorted(set(value) - _%s_KEYS):" % name.upper())
        lines.append("        errors.append(\"unexpected field %r\" % (key,))")
    for key, spec, _req in fields_of(schema):
        get = "value[%r]" % key
        constraints: List[str] = []
        enum = spec.get("enum")
        if enum:
            constraints.append("            if %s not in %r:" % (get, tuple(enum)))
            constraints.append("                errors.append(%r)" % ("%s: must be one of %s" % (key, ", ".join(map(str, enum)))))
        if "minimum" in spec:
            constraints.append("            if %s < %r:" % (get, spec["minimum"]))
            constraints.append("                errors.append(%r)" % ("%s: below minimum %s" % (key, spec["minimum"])))
        if "maximum" in spec:
            constraints.append("            if %s > %r:" % (get, spec["maximum"]))
            constraints.append("                errors.append(%r)" % ("%s: above maximum %s" % (key, spec["maximum"])))
        if spec.get("minLength"):
            constraints.append("            if len(%s) < %d:" % (get, spec["minLength"]))
            constraints.append("                errors.append(%r)" % ("%s: shorter than %d" % (key, spec["minLength"])))
        lines.append("    if %r in value:" % key)
        lines.append("        if not (%s):" % _python_type_check(get, spec["type"]))
        lines.append("            errors.append(%r)" % ("%s: expected %s" % (key, spec["type"])))
        if constraints:
            lines.append("        else:")
            lines.extend(constraints)
    lines.append("    return errors")
    return lines


# -- Go ---------------------------------------------------------------------

def emit_go(schemas: List[Dict[str, Any]]) -> str:
    lines = ["// " + HEADER, "//", "// Regenerate with: python tools/codegen_schemas.py --only go", "",
             "package main", "", 'import (', '\t"encoding/json"', '\t"fmt"', ')', ""]
    for schema in schemas:
        # `Document` suffix on purpose: the relay already owns accumulator types
        # (ProxyTelemetry). The generated type is the *wire* document, and naming it
        # apart keeps the two from silently merging into one struct with two meanings.
        cls = pascal(schema["$id"]) + "Document"
        lines.append("// %s mirrors schema/%s." % (cls, schema["_file"]))
        lines.append("type %s struct {" % cls)
        for key, spec, req in fields_of(schema):
            base = GO_SCALARS.get(spec["type"]) or GO_CONTAINERS[spec["type"]]
            if not req and spec["type"] in GO_SCALARS:
                base = "*" + base
            tag = key + ("" if req else ",omitempty")
            lines.append('\t%s %s `json:"%s"`' % (pascal(key), base, tag))
        lines.append("}")
        lines.append("")
        lines.extend(_go_parser(cls, schema))
        lines.append("")
    lines.extend([
        "func isaString(v interface{}) bool  { _, ok := v.(string); return ok }",
        "func isaBool(v interface{}) bool    { _, ok := v.(bool); return ok }",
        "func isaNumber(v interface{}) bool  { _, ok := v.(float64); return ok }",
        "func isaInteger(v interface{}) bool { n, ok := v.(float64); return ok && n == float64(int64(n)) }",
        "func isaObject(v interface{}) bool  { _, ok := v.(map[string]interface{}); return ok }",
        "func isaArray(v interface{}) bool   { _, ok := v.([]interface{}); return ok }",
        "",
    ])
    return "\n".join(lines)


def _go_check(var: str, kind: str) -> str:
    return {
        "string": 'isaString(%s)' % var,
        "integer": 'isaInteger(%s)' % var,
        "number": 'isaNumber(%s)' % var,
        "boolean": 'isaBool(%s)' % var,
        "object": 'isaObject(%s)' % var,
        "array": 'isaArray(%s)' % var,
    }[kind]


def _go_parser(cls: str, schema: Dict[str, Any]) -> List[str]:
    name = schema["$id"]
    keys = sorted(key for key, _spec, _req in fields_of(schema))
    lines = ["// %sKeys is the envelope's closed key set." % name.upper(),
             "var %sKeys = []string{%s}" % (name, ", ".join('"%s"' % k for k in keys)), "",
             "// Parse%s decodes and validates one %s document." % (cls, name),
             "func Parse%s(raw []byte) (*%s, []string) {" % (cls, cls),
             "\tvar probe map[string]interface{}",
             "\tif err := json.Unmarshal(raw, &probe); err != nil {",
             '\t\treturn nil, []string{"body is not a JSON object: " + err.Error()}',
             "\t}",
             "\terrors := %sValidate(probe)" % name,
             "\tif len(errors) > 0 {",
             "\t\treturn nil, errors",
             "\t}",
             "\tvar out %s" % cls,
             "\tif err := json.Unmarshal(raw, &out); err != nil {",
             '\t\treturn nil, []string{"decode failed: " + err.Error()}',
             "\t}",
             "\treturn &out, nil",
             "}", "",
             "// %sValidate checks the raw map so a missing key is distinguishable from a zero value." % name,
             "func %sValidate(value map[string]interface{}) []string {" % name,
             "\terrors := []string{}"]
    required = [key for key, _spec, req in fields_of(schema) if req]
    for key in required:
        lines.append('\tif _, ok := value["%s"]; !ok {' % key)
        lines.append('\t\terrors = append(errors, "missing required field %s")' % key)
        lines.append("\t}")
    if extra_policy(schema):
        lines.append("\tfor key := range value {")
        lines.append("\t\tknown := false")
        lines.append("\t\tfor _, allowed := range %sKeys {" % name)
        lines.append("\t\t\tif key == allowed {")
        lines.append("\t\t\t\tknown = true")
        lines.append("\t\t\t\tbreak")
        lines.append("\t\t\t}")
        lines.append("\t\t}")
        lines.append("\t\tif !known {")
        lines.append('\t\t\terrors = append(errors, fmt.Sprintf("unexpected field %q", key))')
        lines.append("\t\t}")
        lines.append("\t}")
    for key, spec, _req in fields_of(schema):
        v = 'value["%s"]' % key
        lines.append('\tif raw, ok := %s; ok {' % v)
        lines.append("\t\tif !(%s) {" % _go_check("raw", spec["type"]))
        lines.append('\t\t\terrors = append(errors, "%s: expected %s")' % (key, spec["type"]))
        lines.append("\t\t} else {")
        enum = spec.get("enum")
        if enum:
            quoted = ", ".join('"%s"' % item for item in enum)
            lines.append("\t\t\tallowed := []string{%s}" % quoted)
            lines.append("\t\t\tmatch := false")
            lines.append("\t\t\tfor _, candidate := range allowed {")
            lines.append("\t\t\t\tif raw == candidate {")
            lines.append("\t\t\t\t\tmatch = true")
            lines.append("\t\t\t\t}")
            lines.append("\t\t\t}")
            lines.append("\t\t\tif !match {")
            lines.append('\t\t\t\terrors = append(errors, fmt.Sprintf("%s: must be one of %%v", allowed))' % key)
            lines.append("\t\t\t}")
        if "minimum" in spec:
            lines.append("\t\t\tif number, ok := raw.(float64); ok && number < %s {" % spec["minimum"])
            lines.append('\t\t\t\terrors = append(errors, "%s: below minimum %s")' % (key, spec["minimum"]))
            lines.append("\t\t\t}")
        if "maximum" in spec:
            lines.append("\t\t\tif number, ok := raw.(float64); ok && number > %s {" % spec["maximum"])
            lines.append('\t\t\t\terrors = append(errors, "%s: above maximum %s")' % (key, spec["maximum"]))
            lines.append("\t\t\t}")
        if spec.get("minLength"):
            lines.append("\t\t\tif text, ok := raw.(string); ok && len(text) < %d {" % spec["minLength"])
            lines.append('\t\t\t\terrors = append(errors, "%s: shorter than %d")' % (key, spec["minLength"]))
            lines.append("\t\t\t}")
        lines.append("\t\t}")
        lines.append("\t}")
    lines.append("\treturn errors")
    lines.append("}")
    lines.append("")
    lines.append("// Encode%s renders the typed value as the canonical document." % cls)
    lines.append("func Encode%s(value *%s) ([]byte, error) {" % (cls, cls))
    lines.append("\treturn json.Marshal(value)")
    lines.append("}")
    lines.append("")
    return lines


# -- C# ---------------------------------------------------------------------

def emit_csharp(schemas: List[Dict[str, Any]]) -> str:
    lines = ["// " + HEADER, "//", "// Regenerate with: python tools/codegen_schemas.py --only csharp", "",
             "using System;", "using System.Collections.Generic;", "using DofusFarm.Json;", "",
             "namespace DofusFarm.Contracts", "{", "    public static class ContractIds", "    {"]
    for schema in schemas:
        lines.append("        public const string %s = \"%s\";" % (pascal(schema["$id"]), schema["$id"]))
    lines.append("    }")
    for schema in schemas:
        lines.append("")
        lines.extend(_csharp_contract(schema))
    lines.append("}")
    return "\n".join(lines)


def _cs_check(expr: str, kind: str) -> str:
    return {
        "string": "%s is string" % expr,
        "integer": "%s is long" % expr,
        "number": "(%s is long || %s is double)" % (expr, expr),
        "boolean": "%s is bool" % expr,
        "object": "%s is Dictionary<string, object>" % expr,
        "array": "%s is List<object>" % expr,
    }[kind]


def _cs_number(expr: str) -> str:
    return "(%s is long ? (double)(long)%s : (double)%s)" % (expr, expr, expr)


def _csharp_contract(schema: Dict[str, Any]) -> List[str]:
    name = schema["$id"]
    cls = pascal(name)
    fields = fields_of(schema)
    lines = ["    public sealed class %s" % cls, "    {"]
    value_types = ("long", "double", "bool")
    for key, spec, req in fields:
        base = CS_SCALARS.get(spec["type"]) or CS_CONTAINERS[spec["type"]]
        if not req and base in value_types:
            base = "Nullable<" + base + ">"
        lines.append("        public %s %s;" % (base, pascal(key)))
    if any(req for _k, _s, req in fields if _s["type"] == "object"):
        pass
    lines.append("")
    lines.append("        public static readonly string[] Keys = new string[] { %s };"
                 % ", ".join("\"%s\"" % key for key, _spec, _req in fields))
    lines.append("")
    lines.extend(_csharp_validator(name, schema, fields))
    lines.append("")
    lines.extend(_csharp_parse(cls, name, fields))
    lines.append("")
    lines.extend(_csharp_encode(cls, fields))
    lines.append("    }")
    return lines


def _csharp_validator(name: str, schema: Dict[str, Any], fields) -> List[str]:
    lines = ["        /// <summary>Every violation of schema/%s.schema.json; empty means valid.</summary>" % name,
             "        public static List<string> Validate(Dictionary<string, object> value)",
             "        {",
             "            List<string> errors = new List<string>();",
             "            if (value == null)",
             "            {",
             "                errors.Add(\"expected an object, got null\");",
             "                return errors;",
             "            }"]
    required = sorted(key for key, _spec, req in fields if req)
    for key in required:
        lines.append("            if (!value.ContainsKey(\"%s\")) errors.Add(\"missing required field '%s'\");" % (key, key))
    if extra_policy(schema):
        lines.append("            foreach (string key in value.Keys)")
        lines.append("                if (Array.IndexOf(Keys, key) < 0) errors.Add(\"unexpected field '\" + key + \"'\");")
    for key, spec, _req in fields:
        lines.append("            {")
        lines.append("                object raw;")
        lines.append("                if (value.TryGetValue(\"%s\", out raw) && raw != null)" % key)
        lines.append("                {")
        lines.append("                    if (!(%s))" % _cs_check("raw", spec["type"]))
        lines.append("                        errors.Add(\"%s: expected %s\");" % (key, spec["type"]))
        lines.append("                    else")
        lines.append("                    {")
        enum = spec.get("enum")
        if enum:
            lines.append("                        string text = raw as string;")
            lines.append("                        if (Array.IndexOf(new string[] { %s }, text) < 0)"
                         % ", ".join("\"%s\"" % item for item in enum))
            lines.append("                            errors.Add(\"%s: must be one of %s\");"
                         % (key, ", ".join(enum)))
        if "minimum" in spec:
            lines.append("                        if (%s < %s) errors.Add(\"%s: below minimum %s\");"
                         % (_cs_number("raw"), spec["minimum"], key, spec["minimum"]))
        if "maximum" in spec:
            lines.append("                        if (%s > %s) errors.Add(\"%s: above maximum %s\");"
                         % (_cs_number("raw"), spec["maximum"], key, spec["maximum"]))
        if spec.get("minLength"):
            lines.append("                        string asText = raw as string;")
            lines.append("                        if (asText != null && asText.Length < %d) errors.Add(\"%s: shorter than %d\");"
                         % (spec["minLength"], key, spec["minLength"]))
        lines.append("                    }")
        lines.append("                }")
        lines.append("            }")
    lines.append("            return errors;")
    lines.append("        }")
    return lines


def _csharp_parse(cls: str, name: str, fields) -> List[str]:
    lines = ["        /// <summary>Parse and validate one %s document.</summary>" % name,
             "        public static bool TryParse(string json, out %s value, out List<string> errors)" % cls,
             "        {",
             "            value = null;",
             "            errors = new List<string>();",
             "            Dictionary<string, object> map = JsonText.TryParseObject(json);",
             "            if (map == null)",
             "            {",
             "                errors.Add(\"body is not a JSON object\");",
             "                return false;",
             "            }",
             "            errors.AddRange(Validate(map));",
             "            if (errors.Count > 0) return false;",
             "",
             "            %s parsed = new %s();" % (cls, cls)]
    for key, spec, req in fields:
        p = pascal(key)
        if spec["type"] == "string":
            lines.append("            parsed.%s = JsonText.String(map, \"%s\", null);" % (p, key))
        elif spec["type"] == "integer":
            if req:
                lines.append("            parsed.%s = JsonText.Long(map, \"%s\", 0);" % (p, key))
            else:
                lines.append("            if (map.ContainsKey(\"%s\")) parsed.%s = JsonText.Long(map, \"%s\", 0);" % (key, p, key))
        elif spec["type"] == "number":
            if req:
                lines.append("            parsed.%s = JsonText.Double(map, \"%s\", 0);" % (p, key))
            else:
                lines.append("            if (map.ContainsKey(\"%s\")) parsed.%s = JsonText.Double(map, \"%s\", 0);" % (key, p, key))
        elif spec["type"] == "boolean":
            if req:
                lines.append("            parsed.%s = JsonText.Bool(map, \"%s\", false);" % (p, key))
            else:
                lines.append("            if (map.ContainsKey(\"%s\")) parsed.%s = JsonText.Bool(map, \"%s\", false);" % (key, p, key))
        elif spec["type"] == "object":
            lines.append("            parsed.%s = JsonText.Object(map, \"%s\");" % (p, key))
        else:
            lines.append("            parsed.%s = JsonText.Array(map, \"%s\");" % (p, key))
    lines.extend(["",
                  "            value = parsed;",
                  "            return true;",
                  "        }"])
    return lines


def _csharp_encode(cls: str, fields) -> List[str]:
    lines = ["        /// <summary>Canonical document for this value; absent optionals stay absent.</summary>",
             "        public string ToJson()",
             "        {",
             "            Dictionary<string, object> map = new Dictionary<string, object>(StringComparer.Ordinal);"]
    for key, spec, req in fields:
        p = pascal(key)
        if spec["type"] in ("integer", "number", "boolean"):
            if req:
                lines.append("            map[\"%s\"] = %s;" % (key, p))
            else:
                lines.append("            if (%s.HasValue) map[\"%s\"] = %s.Value;" % (p, key, p))
        else:
            lines.append("            if (%s != null) map[\"%s\"] = %s;" % (p, key, p))
    lines.extend(["            return JsonText.Serialize(map);", "        }"])
    return lines


# -- JavaScript -------------------------------------------------------------

def emit_js(schemas: List[Dict[str, Any]]) -> str:
    lines = ["// " + HEADER, "//", "// Regenerate with: python tools/codegen_schemas.py --only js",
             "(function (root) {", "    'use strict';", "",
             "    function isObject(v) { return v !== null && typeof v === 'object' && !Array.isArray(v); }",
             "    function isString(v) { return typeof v === 'string'; }",
             "    function isBool(v) { return typeof v === 'boolean'; }",
             "    function isNumber(v) { return typeof v === 'number' && isFinite(v); }",
             "    function isInteger(v) { return isNumber(v) && Math.floor(v) === v; }",
             "    function isArray(v) { return Array.isArray(v); }", ""]
    for schema in schemas:
        name = schema["$id"]
        fn = "validate" + pascal(name)
        lines.append("    var %s_KEYS = [%s];" % (name.upper(), ", ".join("'%s'" % k for k in sorted(
            key for key, _spec, _req in fields_of(schema)))))
        lines.append("")
        lines.append("    function %s(value) {" % fn)
        lines.append("        var errors = [];")
        lines.append("        if (!isObject(value)) { return ['expected an object, got ' + typeof value]; }")
        required = [key for key, _spec, req in fields_of(schema) if req]
        for key in sorted(required):
            lines.append("        if (!Object.prototype.hasOwnProperty.call(value, '%s')) { errors.push(\"missing required field '%s'\"); }" % (key, key))
        if extra_policy(schema):
            lines.append("        Object.keys(value).forEach(function (key) {")
            lines.append("            if (%s_KEYS.indexOf(key) < 0) { errors.push('unexpected field ' + key); }" % name.upper())
            lines.append("        });")
        for key, spec, _req in fields_of(schema):
            checker = {"string": "isString", "integer": "isInteger", "number": "isNumber",
                       "boolean": "isBool", "object": "isObject", "array": "isArray"}[spec["type"]]
            lines.append("        if (Object.prototype.hasOwnProperty.call(value, '%s') && !%s(value['%s'])) {" % (key, checker, key))
            lines.append("            errors.push('%s: expected %s');" % (key, spec["type"]))
            lines.append("        }")
            enum = spec.get("enum")
            if enum:
                lines.append("        if (isString(value['%s']) && [%s].indexOf(value['%s']) < 0) {" % (
                    key, ", ".join("'%s'" % item for item in enum), key))
                lines.append("            errors.push('%s: must be one of %s');" % (key, ", ".join(enum)))
                lines.append("        }")
            if "minimum" in spec:
                lines.append("        if (isNumber(value['%s']) && value['%s'] < %s) { errors.push('%s: below minimum %s'); }"
                             % (key, key, spec["minimum"], key, spec["minimum"]))
            if "maximum" in spec:
                lines.append("        if (isNumber(value['%s']) && value['%s'] > %s) { errors.push('%s: above maximum %s'); }"
                             % (key, key, spec["maximum"], key, spec["maximum"]))
            if spec.get("minLength"):
                lines.append("        if (isString(value['%s']) && value['%s'].length < %d) { errors.push('%s: shorter than %d'); }"
                             % (key, key, spec["minLength"], key, spec["minLength"]))
        lines.append("        return errors;")
        lines.append("    }")
        lines.append("")
        lines.append("    function encode%s(value) {" % pascal(name))
        lines.append("        var errors = %s(value);" % fn)
        lines.append("        if (errors.length) { throw new Error('%s: ' + errors.join('; ')); }" % name)
        lines.append("        var out = {};")
        lines.append("        %s_KEYS.forEach(function (key) {" % name.upper())
        lines.append("            if (value[key] !== undefined) { out[key] = value[key]; }")
        lines.append("        });")
        lines.append("        return out;")
        lines.append("    }")
        lines.append("")
    lines.append("    var CONTRACTS = {")
    for schema in schemas:
        lines.append("        '%s': validate%s," % (schema["$id"], pascal(schema["$id"])))
    lines.append("    };")
    lines.append("")
    lines.append("    root.DofusContracts = {")
    lines.append("        ids: " + repr([schema["$id"] for schema in schemas]).replace("'", '"') + ",")
    lines.append("        validate: function (name, value) {")
    lines.append("            var fn = CONTRACTS[name];")
    lines.append("            return fn ? fn(value) : ['unknown contract ' + name];")
    lines.append("        },")
    for schema in schemas:
        p = pascal(schema["$id"])
        lines.append("        validate%s: validate%s," % (p, p))
        lines.append("        encode%s: encode%s," % (p, p))
    lines[-1] = lines[-1].rstrip(",")
    lines.append("    };")
    lines.append("    if (typeof module !== 'undefined' && module.exports) { module.exports = root.DofusContracts; }")
    lines.append("})(typeof globalThis !== 'undefined' ? globalThis : this);")
    lines.append("")
    return "\n".join(lines)


# -- driver -----------------------------------------------------------------

def build_outputs(schemas: List[Dict[str, Any]]) -> Dict[str, str]:
    return {
        "python": emit_python(schemas),
        "go": emit_go(schemas),
        "csharp": emit_csharp(schemas),
        "js": emit_js(schemas),
    }


def manifest_for(schemas: List[Dict[str, Any]], outputs: Dict[str, str]) -> Dict[str, Any]:
    return {
        "version": 1,
        "generator": "tools/codegen_schemas.py",
        "inputs": {schema["_file"]: hashlib.sha256(schema["_source"]).hexdigest() for schema in schemas},
        "outputs": {name: hashlib.sha256(text.encode("utf-8")).hexdigest()
                    for name, text in sorted(outputs.items())},
    }


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift and write nothing")
    parser.add_argument("--only", choices=sorted(TARGETS), help="regenerate one target")
    args = parser.parse_args(argv)

    schemas = load_schemas()
    outputs = build_outputs(schemas)
    manifest = manifest_for(schemas, outputs)
    manifest_text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"

    if args.check:
        drift = []
        for name, text in outputs.items():
            if args.only and name != args.only:
                continue
            path = TARGETS[name]
            if not path.is_file():
                drift.append("%s: missing" % path.relative_to(ROOT))
            elif path.read_text(encoding="utf-8") != text:
                drift.append("%s: out of date" % path.relative_to(ROOT))
        if not args.only:
            if not MANIFEST.is_file():
                drift.append("%s: missing" % MANIFEST.relative_to(ROOT))
            elif MANIFEST.read_text(encoding="utf-8") != manifest_text:
                drift.append("%s: out of date" % MANIFEST.relative_to(ROOT))
        if drift:
            for item in drift:
                print("codegen drift: " + item, file=sys.stderr)
            print("run: python tools/codegen_schemas.py", file=sys.stderr)
            return 1
        print("codegen: %d contracts, %d targets, no drift" % (len(schemas), len(outputs)))
        return 0

    for name, text in outputs.items():
        if args.only and name != args.only:
            continue
        path = TARGETS[name]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print("wrote %s" % path.relative_to(ROOT))
    if not args.only:
        MANIFEST.write_text(manifest_text, encoding="utf-8", newline="\n")
        print("wrote %s" % MANIFEST.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
